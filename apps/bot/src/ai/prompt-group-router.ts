export type PromptGroup =
  | "expense"
  | "absence"
  | "task-status"
  | "collaboration"
  | "task-list"
  | "create-task-rich"
  | "create-note"
  | "classifier";

function normalizeForRouting(text: string): string {
  return text
    .trim()
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/\s+/g, " ");
}

const TASK_LIST_MARKERS = [
  "мои задачи",
  "покажи мои задачи",
  "покажи задачи",
  "что у меня по задачам",
  "какие у меня задачи",
  "что мне нужно сделать",
  "что мне делать",
  "что мне сделать",
  "задачи у меня",
  "неподтвержденные расходы",
  "неподтверждённые расходы",
  "расходы без чеков",
  "чеки к расходам",
  "что у меня без чеков",
  "где я не приложил чеки",
  "какие чеки я должен загрузить",
] as const;

const TASK_LIST_USER_PATTERNS = [
  /какие(?: сейчас)? задачи у /,
  /что(?: сейчас)? у .+ (?:в работе|по задачам)/,
  /покажи(?: список)? задач[и]? /,
  /список задач /,
  /^задачи /,
  /чем занят/,
  /что делает /,
  /задачи у /,
] as const;

/** Детерминированный выбор группы промпта перед вызовом YandexGPT. */
export function resolvePromptGroup(userText: string): PromptGroup {
  const t = normalizeForRouting(userText);
  if (!t) return "classifier";

  if (TASK_LIST_MARKERS.some((m) => t.includes(m))) {
    return "task-list";
  }
  if (TASK_LIST_USER_PATTERNS.some((re) => re.test(t))) {
    return "task-list";
  }

  if (
    /(?:^|\s)(?:потратил|потратила|потратили|расход|израсходовал|израсходовала|заплатил|заплатила|оплатил|оплатила|купил|купила|купили)(?:\s|$)/.test(
      t,
    ) ||
    /(?:создай|добавь|создайте|добавьте)\s+бюджет/.test(t)
  ) {
    return "expense";
  }

  if (
    /заболел|заболела|болею|болеет|больничн|отпуск|удали больничн|отмени отпуск|удали отпуск|отмени больничн/.test(
      t,
    )
  ) {
    return "absence";
  }

  if (
    /закрыл(?:а|и)?\s+задачу|закрыла\s+задачу|закрыли\s+задачу|закрой\s+задачу|закрыть\s+задачу|завершил(?:а)?\s+задачу|завершила\s+задачу|выполнил(?:а)?\s+задачу|выполнила\s+задачу|сделал(?:а)?\s+задачу|сделала\s+задачу|задача\s+готова|готово\s+задачу|начал(?:а)?\s+задачу|начать\s+задачу|начни\s+задачу|беру\s+задачу|взял(?:а)?\s+задачу|взяла\s+задачу|в\s+работу\s+задачу|начал\s+делать|беру\s+в\s+работу|взял\s+в\s+работу|отмени\s+задачу|отменить\s+задачу|отменяю\s+задачу|дедлайн/.test(
      t,
    )
  ) {
    return "task-status";
  }

  if (/коммент|комментар/.test(t)) {
    return "collaboration";
  }

  if (/(?:^|\s)(?:позови|позвати|упомяни|упомянуть)(?:\s|$)/.test(t)) {
    return "collaboration";
  }

  if (
    /передай задачу|передать задачу|перекинь|переназначь|перенеси задачу|переведи задачу|сними задачу|передай мне задачу|перекинь мне задачу|перенеси мне задачу|переведи на меня|забери мне задачу|назначь мне задачу|призови/.test(
      t,
    )
  ) {
    return "collaboration";
  }

  if (
    /(?:создай|поставь|заведи|завести|назначь|дай)(?:те)?\s+(?:задачу|хадачу)/.test(t) ||
    /(?:нужно|надо)\s+завести\s+задачу/.test(t) ||
    /(?:задачу|задача)\s+на\s+\p{L}/u.test(t) ||
    /(?:задачу|задача)\s+для\s+\p{L}/u.test(t) ||
    /(?:создай|поставь|назначь|дай)(?:те)?\s+\p{L}+\s+(?:задачу|хадачу)/u.test(t) ||
    /(?:создай|поставь|назначь|дай)(?:те)?\s+мне(?:\s|$)/.test(t) ||
    /^поручи(?:те)?\s+/u.test(t) ||
    /^пусть\s+\p{L}/u.test(t) ||
    /запиши(?:те)?\s+мне\s+(?:в\s+)?задач/i.test(t)
  ) {
    return "create-task-rich";
  }

  return "classifier";
}
